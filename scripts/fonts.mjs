// Copies only the font subsets we use (latin, latin-ext, devanagari) into public/fonts
// and writes styles/fonts.css. Self-hosted: no request to Google at runtime.
import fs from 'node:fs'
import path from 'node:path'

const root = path.resolve(import.meta.dirname, '..')
const nm = (p) => path.join(root, 'node_modules', p)
const out = path.join(root, 'public/fonts')
fs.mkdirSync(out, { recursive: true })

const sources = [
  { css: '@fontsource-variable/anek-latin/wdth.css', family: 'Anek Latin', subsets: ['latin', 'latin-ext'] },
  // Devanagari display uses the weight-only file (257 KB) instead of the width axis file (726 KB).
  { css: '@fontsource-variable/anek-devanagari/wght.css', family: 'Anek Devanagari', subsets: ['devanagari'] },
  ...[400, 500, 600, 700].map((w) => ({ css: `@fontsource/mukta/${w}.css`, family: 'Mukta', subsets: w === 400 || w === 600 ? ['latin', 'latin-ext', 'devanagari'] : ['latin', 'latin-ext'] })),
  { css: '@fontsource/kalam/400.css', family: 'Kalam', subsets: ['latin', 'devanagari'] },
]

let css = '/* generated by scripts/fonts.mjs: do not edit */\n'
for (const s of sources) {
  const text = fs.readFileSync(nm(s.css), 'utf8')
  const blocks = text.split('@font-face').slice(1)
  for (const b of blocks) {
    const url = /url\(\.\/files\/([^)]+\.woff2)\)/.exec(b)?.[1]
    if (!url) continue
    const prefix = s.css.split('/')[1] + '-'
    const rest = url.slice(prefix.length)
    const subset = s.subsets.find((x) => rest.startsWith(`${x}-`) && !(x === 'latin' && rest.startsWith('latin-ext')))
    if (!subset) continue
    fs.copyFileSync(path.join(path.dirname(nm(s.css)), 'files', url), path.join(out, url))
    const body = b
      .replace(/font-family:[^;]+;/, `font-family: '${s.family}';`)
      .replace(/src:[^;]+;/, `src: url(/fonts/${url}) format('woff2');`)
    css += `@font-face${body.trim().replace(/\n\s*\n/g, '\n')}\n`
  }
}
fs.writeFileSync(path.join(root, 'styles/fonts.css'), css)
console.log('fonts:', fs.readdirSync(out).length, 'files')
